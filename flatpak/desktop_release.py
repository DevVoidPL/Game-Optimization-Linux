#!/usr/bin/env python3
"""Build-only Desktop compiler and fail-closed release inspection."""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET

RESOURCE_TYPES = {
    "resources": {".png", ".svg", ".jpg", ".jpeg", ".webp"},
    "assets/branding": {".png", ".svg"},
    "translations": {".qm"},
}
FORBIDDEN_SUFFIXES = {".py", ".pyc", ".pyo", ".pyi", ".qml", ".ts", ".c", ".cpp", ".h", ".a", ".o", ".whl", ".toml", ".cmake"}
FORBIDDEN_PARTS = {"tests", "test", "__pycache__", ".git", ".github", "build", "prompts", "sessions", "node_modules"}
FORBIDDEN_NAMES = {"manifest.json", "pyproject.toml", "setup.py", "setup.cfg", "agents.md", "claude.md", "gemini.md", "cmakecache.txt", "qmldir"}
MARKERS = (b"generated by chatgpt", b"generated by claude", b"co-authored-by: claude", b"co-authored-by: chatgpt", b"<command-instructions>", b"<user_input mode=")


def resource_files(package):
    for directory, suffixes in RESOURCE_TYPES.items():
        for path in sorted((package / directory).rglob("*")):
            if path.is_file() and not path.is_symlink() and path.suffix.lower() in suffixes:
                yield path


def audit_tree(root):
    if not root.is_dir():
        return [f"{root}: release directory does not exist"]
    errors = []
    for path in sorted(root.rglob("*")):
        relative = path.relative_to(root)
        parts = {part.lower() for part in relative.parts}
        name = path.name.lower()
        if not path.is_file() and not path.is_symlink():
            continue
        if (path.suffix.lower() in FORBIDDEN_SUFFIXES or parts & FORBIDDEN_PARTS
                or name in FORBIDDEN_NAMES or any(part.endswith((".dist-info", ".egg-info", ".build")) for part in parts)
                or "nuitka" in name or name.endswith((".debug", ".map"))):
            errors.append(f"{relative}: source/build/development artifact")
        if path.is_symlink():
            if not path.resolve().is_relative_to(root.resolve()) or not path.exists():
                errors.append(f"{relative}: escaping or broken symlink")
            continue
        with path.open("rb") as stream:
            head = stream.read(4096)
            if head.startswith(b"#!") and b"python" in head.split(b"\n", 1)[0].lower():
                errors.append(f"{relative}: Python source executable")
            stream.seek(0)
            tail = b""
            while chunk := stream.read(1024 * 1024):
                lowered = (tail + chunk).lower()
                if any(marker in lowered for marker in MARKERS):
                    errors.append(f"{relative}: development attribution/prompt marker")
                    break
                tail = chunk[-128:]
    return errors


def audit_report(report, package):
    modules = {item.get("name"): item.get("kind") for item in ET.parse(report).iter("module")}
    errors = []
    for path in package.rglob("*.py"):
        parts = list(path.relative_to(package.parent).with_suffix("").parts)
        if parts[-1] == "__init__":
            parts.pop()
        name = ".".join(parts)
        if modules.get(name) not in {"CompiledPythonModule", "CompiledPythonPackage"}:
            errors.append(f"{name}: not compiled ({modules.get(name, 'missing')})")
    return errors


def compiler_command(root, work, entry):
    command = [sys.executable, "-m", "nuitka", "--standalone", "--onefile", "--follow-imports",
               "--include-package=game_optimization_linux", "--enable-plugin=pyside6",
               "--include-qt-plugins=platforms,imageformats", "--deployment", "--python-flag=no_docstrings",
               "--assume-yes-for-downloads", "--static-libpython=no", "--output-filename=game-optimization-linux",
               f"--output-dir={work}", f"--report={work / 'compilation-report.xml'}"]
    package = root / "src/game_optimization_linux"
    for path in resource_files(package):
        command.append(f"--include-data-files={path}=game_optimization_linux/{path.relative_to(package).as_posix()}")
    command.append(str(entry))
    return command


def require_clean(root):
    errors = audit_tree(root)
    if errors:
        raise RuntimeError("Release audit rejected:\n" + "\n".join(errors))


def build(root, prefix, work):
    root, prefix, work = root.resolve(), prefix.resolve(), work.resolve()
    if prefix != Path("/app"):
        raise RuntimeError("Build installation is restricted to the Flatpak /app prefix")
    work.mkdir(parents=True, exist_ok=True)
    environment = dict(os.environ, PYTHONPATH=str(root / "src"))
    # Keep .dist and XML outside /app: audit the actual onefile inputs.
    subprocess.run(compiler_command(root, work, root / "flatpak/desktop_entry.py"), env=environment, check=True)
    errors = audit_report(work / "compilation-report.xml", root / "src/game_optimization_linux")
    if errors:
        raise RuntimeError("Compilation coverage rejected:\n" + "\n".join(errors))
    dist = work / "desktop_entry.dist"
    if not dist.is_dir():
        raise RuntimeError("Nuitka standalone payload is missing; cannot audit onefile")
    require_clean(dist)
    binary = work / "game-optimization-linux"
    if binary.read_bytes()[:4] != b"\x7fELF":
        raise RuntimeError("Compiler output is not a native ELF executable")
    # Do not let source PYTHONPATH mask missing compiled imports in this test.
    runtime_environment = dict(os.environ)
    runtime_environment.pop("PYTHONPATH", None)
    subprocess.run([str(binary), "--release-self-test"], env=runtime_environment, cwd=work, check=True)
    (prefix / "bin").mkdir(exist_ok=True)
    shutil.copy2(binary, prefix / "bin/game-optimization-linux")
    (prefix / "bin/game-optimization-run").write_text('#!/bin/sh\nexec /app/bin/game-optimization-linux --release-runner "$@"\n')
    (prefix / "bin/game-optimization-run").chmod(0o755)
    # Keep legally required notices, never remove them to conceal provenance.
    licenses = prefix / "share/licenses/game-optimization-linux"
    licenses.mkdir(parents=True, exist_ok=True)
    shutil.copy2(root / "LICENSE", licenses / "LICENSE")
    for site in (prefix / "lib").glob("python*/site-packages"):
        for metadata in site.glob("*.dist-info"):
            for path in metadata.rglob("*"):
                if path.is_file() and ("license" in path.name.lower() or "notice" in path.name.lower() or "licenses" in path.parts):
                    target = licenses / metadata.name.removesuffix(".dist-info") / path.relative_to(metadata)
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(path, target)
        # The executable owns its compiled dependencies; pip/compiler trees are build-only.
        shutil.rmtree(site)
    for path in (prefix / "bin").iterdir():
        # Remove Python dependency/compiler console scripts, not btrfs tools.
        if path.is_file():
            with path.open("rb") as stream:
                first = stream.readline(4096)
            if first.startswith(b"#!") and b"python" in first.lower():
                path.unlink()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="operation", required=True)
    compile_parser = commands.add_parser("build")
    compile_parser.add_argument("--root", type=Path, default=Path.cwd())
    compile_parser.add_argument("--prefix", type=Path, default=Path("/app"))
    compile_parser.add_argument("--work", type=Path, default=Path("/run/build/desktop-compiled"))
    audit_parser = commands.add_parser("audit")
    audit_parser.add_argument("root", type=Path)
    args = parser.parse_args()
    if args.operation == "build":
        build(args.root, args.prefix, args.work)
    else:
        require_clean(args.root)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())