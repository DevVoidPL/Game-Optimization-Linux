#!/usr/bin/env python3
"""Generate the sandbox-compiled GTK Desktop manifest without modifying Couch."""
from __future__ import annotations

from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "io.github.DevVoidPL.GameOptimizationLinux.yml"
TARGET = HERE / "io.github.DevVoidPL.GameOptimizationLinux.desktop-edition.yml"
ANCHOR = "      - python3 -m pip install --no-index --no-deps --no-build-isolation --prefix=${FLATPAK_DEST} .\n"
BUILD_DEPS = """  - name: build-tools
    buildsystem: simple
    build-commands:
      - python3 -m pip install --no-index --no-deps --no-build-isolation --prefix=${FLATPAK_DEST} compiler/*
      - /app/bin/patchelf --version
    sources:
      - type: file
        url: https://files.pythonhosted.org/packages/a6/b8/5c58a2c4d66631ec12eb641c08b7a31116d972c4ccbb0a340a047db51238/nuitka-2.8.10.tar.gz
        sha256: 03e4d0756d8a11cb2627da3a2d9b518c802d031bf4f2c629e0a7b8c773497452
        dest: compiler
      - type: file
        url: https://files.pythonhosted.org/packages/33/55/af02708f230eb77084a299d7b08175cff006dea4f2721074b92cdb0296c0/ordered_set-4.1.0-py3-none-any.whl
        sha256: 046e1132c71fcf3330438a539928932caf51ddbc582496833e23de611de14562
        dest: compiler
      - type: file
        url: https://files.pythonhosted.org/packages/63/4b/e3678b4e776db00f9f7b2fe58e547e8928ef32727d7a1ff01dea010f3f13/zstandard-0.25.0-cp313-cp313-manylinux2014_x86_64.manylinux_2_17_x86_64.whl
        sha256: 8e735494da3db08694d26480f1493ad2cf86e99bdd53e8e9771b2752a5c0246a
        dest: compiler
      - type: file
        url: https://files.pythonhosted.org/packages/b3/d8/b261671a4064a145ae8129c5585ac79d121d852055043d03b66ee0aa4653/patchelf-0.19.3.0-py3-none-manylinux1_x86_64.manylinux_2_5_x86_64.musllinux_1_1_x86_64.whl
        sha256: 1668a30fcc414debbb1604cd0a361b2f28a33a0ff6e74a74bc71766ee746e21f
        dest: compiler

"""


def main() -> int:
    text = SOURCE.read_text(encoding="utf-8")
    if text.count(ANCHOR) != 1:
        raise SystemExit("The pip install command of the application module was not found exactly once")
    text = text.replace("runtime: org.freedesktop.Platform", "runtime: org.gnome.Platform")
    text = text.replace("runtime-version: '25.08'", "runtime-version: '49'")
    text = text.replace("sdk: org.freedesktop.Sdk", "sdk: org.gnome.Sdk")
    text = text.replace("  - name: game-optimization-linux\n", BUILD_DEPS + "  - name: game-optimization-linux\n")
    # Flatpak's build sandbox may have no loader cache. Nuitka calls ldconfig -p
    # to resolve libraries; generate the cache from sandbox paths only, without
    # altering library symlinks. /etc here is the disposable build sandbox.
    text = text.replace(ANCHOR,
                        "      - /sbin/ldconfig -X -i -C /etc/ld.so.cache /app/lib /usr/lib/x86_64-linux-gnu /usr/lib && python3 flatpak/desktop_release.py build --prefix=${FLATPAK_DEST}\n")
    text = "".join(line for line in text.splitlines(keepends=True)
                   if not (line.lstrip().startswith("- install") and "share/doc/" in line))
    # --build-only skips Builder's cleanup phase. These files were installed
    # into /app by native dependency modules, not supplied by runtime /usr.
    text = text.replace("    sources:\n      - type: dir",
                        "      - rm -rf /app/include /app/lib/debug && rm -f /app/lib/*.a\n"
                        "      - rm -f /app/bin/patchelf\n"
                        "      - python3 flatpak/desktop_release.py audit /app\n"
                        "    sources:\n      - type: dir")
    header = ("# Generated by flatpak/make-desktop-edition-manifest.py; do not edit.\n"
              "# Compiled GTK Desktop only. Couch manifest is unchanged.\n")
    TARGET.write_text(header + text, encoding="utf-8")
    print(TARGET)
    return 0


if __name__ == "__main__":
    sys.exit(main())
