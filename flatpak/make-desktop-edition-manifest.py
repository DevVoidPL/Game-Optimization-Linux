#!/usr/bin/env python3
"""Write the Desktop Edition Flatpak manifest from the main (Couch Edition) one.

Both editions share every dependency module and the whole backend. The Desktop
Edition only adds an edition marker and leaves out the Couch QML and the
assets used exclusively by Couch Mode. Run after changing the main manifest:

    python3 flatpak/make-desktop-edition-manifest.py
"""
from __future__ import annotations

from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "io.github.DevVoidPL.GameOptimizationLinux.yml"
TARGET = HERE / "io.github.DevVoidPL.GameOptimizationLinux.desktop-edition.yml"
ANCHOR = "      - python3 -m pip install --no-index --no-deps --no-build-isolation --prefix=${FLATPAK_DEST} .\n"
# Couch-only icons: referenced only by qml/couch (the MangoHud brand icon is
# also used by Desktop Mode and stays).
DESKTOP_COMMANDS = [
    'PKG="$(echo ${FLATPAK_DEST}/lib/python3*/site-packages/game_optimization_linux)"',
    'test -d "$PKG"',
    'echo desktop > "$PKG/edition.txt"',
    'rm -rf "$PKG/qml/couch"',
    'install -Dm644 "$PKG/assets/ui-icons/couch/actions/mangohud.svg" "$PKG/assets/ui-icons/desktop-keep-mangohud.svg"',
    'rm -rf "$PKG/assets/ui-icons/couch"',
    'install -Dm644 "$PKG/assets/ui-icons/desktop-keep-mangohud.svg" "$PKG/assets/ui-icons/couch/actions/mangohud.svg"',
    'rm -f "$PKG/assets/ui-icons/desktop-keep-mangohud.svg"',
]


def main() -> int:
    text = SOURCE.read_text(encoding="utf-8")
    if text.count(ANCHOR) != 1:
        raise SystemExit("The pip install command of the application module was not found exactly once")
    # Every command is a single shell line, so the PKG variable is set inline.
    joined = " && ".join(DESKTOP_COMMANDS)
    addition = f"      # Desktop Edition: no Couch Mode or controller navigation.\n      - {joined}\n"
    header = ("# GENERATED by flatpak/make-desktop-edition-manifest.py from\n"
              "# io.github.DevVoidPL.GameOptimizationLinux.yml - edit that file instead.\n"
              "# Desktop Edition of Game Optimization Linux (same App ID, alternative install).\n")
    TARGET.write_text(header + text.replace(ANCHOR, ANCHOR + addition), encoding="utf-8")
    print(TARGET)
    return 0


if __name__ == "__main__":
    sys.exit(main())
