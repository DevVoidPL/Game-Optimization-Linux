def test_runner_entry_preserves_arguments(monkeypatch):
    spec = importlib.util.spec_from_file_location("desktop_entry", ROOT / "flatpak/desktop_entry.py")
    entry = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(entry)
    seen = []
    monkeypatch.setattr(entry, "runner_main", lambda arguments: seen.append(arguments) or 7)
    monkeypatch.setattr(sys, "argv", ["game-optimization-linux", "--release-runner", "--appid", "123", "--", "game"])
    assert entry.main() == 7
    assert seen == [["--appid", "123", "--", "game"]]


