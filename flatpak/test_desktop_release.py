"""Desktop release policy; no compiler or Flatpak installation required."""
import importlib.util
from pathlib import Path
import subprocess
import sys

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[1]


def policy():
    path = ROOT / "flatpak/desktop_release.py"
    assert path.is_file(), "Desktop release policy/build driver is missing"
    spec = importlib.util.spec_from_file_location("desktop_release", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_desktop_manifest_compiles_in_sandbox_without_changing_couch():
    couch = ROOT / "flatpak/io.github.DevVoidPL.GameOptimizationLinux.yml"
    before = couch.read_bytes()
    subprocess.run([sys.executable, str(ROOT / "flatpak/make-desktop-edition-manifest.py")], check=True)
    desktop = yaml.safe_load((ROOT / "flatpak/io.github.DevVoidPL.GameOptimizationLinux.desktop-edition.yml").read_text())
    assert desktop["runtime"] == "org.gnome.Platform"
    assert desktop["sdk"] == "org.gnome.Sdk"
    application = desktop["modules"][-1]
    assert application["buildsystem"] == "simple"
    compile_command = "/sbin/ldconfig -X -i -C /etc/ld.so.cache /app/lib /usr/lib/x86_64-linux-gnu /usr/lib && python3 flatpak/desktop_release.py build --prefix=${FLATPAK_DEST}"
    assert compile_command in application["build-commands"]
    assert not any("dist/nuitka" in command for command in application["build-commands"])
    assert not any("pip install" in command for command in application["build-commands"])
    assert not any("share/doc" in command for command in application["build-commands"])
    assert desktop["modules"][-2]["name"] == "build-tools"
    build_deps = desktop["modules"][-2]
    assert build_deps["buildsystem"] == "simple"
    assert "--no-index" in build_deps["build-commands"][0]
    for name in ("nuitka-", "zstandard-", "patchelf-", "ordered_set-"):
        assert any(name in source["url"] and source["sha256"] for source in build_deps["sources"])
    assert any(module["name"] == "python-runtime-dependencies" for module in desktop["modules"])
    assert not any("dist/nuitka" in source.get("path", "") for source in application["sources"])
    assert couch.read_bytes() == before


def test_data_allowlist_excludes_sources_translation_sources_and_couch(tmp_path):
    module = policy()
    package = tmp_path / "game_optimization_linux"
    for relative in ("resources/icon.png", "translations/game_pl.qm", "translations/game_pl.ts", "assets/branding/icon.svg", "qml/Main.qml", "gtk_frontend/window.py", "assets/audio/note.md", "resources/AGENTS.md"):
        target = package / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(b"data")
    assert {str(path.relative_to(package)) for path in module.resource_files(package)} == {"resources/icon.png", "translations/game_pl.qm", "assets/branding/icon.svg"}


@pytest.mark.parametrize("relative", ["game_optimization_linux/main.py", "x.pyc", "Main.qml", "translations/app.ts", "tests/case.txt", "manifest.json", "build/report.xml", "x.dist-info/METADATA", "AGENTS.md", ".git/config", "nuitka-report.xml", "x.a"])
def test_audit_rejects_unwanted_release_files(tmp_path, relative):
    target = tmp_path / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(b"unwanted")
    assert policy().audit_tree(tmp_path), relative


def test_audit_rejects_python_without_extension_and_ai_marker(tmp_path):
    (tmp_path / "helper").write_text("#!/usr/bin/python3\nprint('source')\n")
    (tmp_path / "note.txt").write_text("Generated by ChatGPT\n")
    errors = policy().audit_tree(tmp_path)
    assert any("helper" in error for error in errors)
    assert any("note.txt" in error for error in errors)


def test_audit_allows_native_runtime_and_required_licenses(tmp_path):
    (tmp_path / "program").write_bytes(b"\x7fELF\0native")
    (tmp_path / "LICENSE").write_text("MIT License\n")
    (tmp_path / "config.qm").write_bytes(b"\x00compiled catalog")
    assert policy().audit_tree(tmp_path) == []


def test_report_requires_every_application_module_compiled(tmp_path):
    package = tmp_path / "game_optimization_linux"
    (package / "gtk_frontend").mkdir(parents=True)
    for name in ("__init__.py", "main.py", "gtk_frontend/__init__.py"):
        (package / name).touch()
    report = tmp_path / "report.xml"
    report.write_text('<nuitka-compilation-report><module name="game_optimization_linux" kind="CompiledPythonPackage"/><module name="game_optimization_linux.main" kind="UncompiledPythonModule"/></nuitka-compilation-report>')
    assert policy().audit_report(report, package)
    report.write_text('<nuitka-compilation-report><module name="game_optimization_linux" kind="CompiledPythonPackage"/><module name="game_optimization_linux.main" kind="CompiledPythonModule"/><module name="game_optimization_linux.gtk_frontend" kind="CompiledPythonPackage"/></nuitka-compilation-report>')
    assert policy().audit_report(report, package) == []


def test_compiler_uses_report_package_and_native_frontend(tmp_path):
    module = policy()
    command = module.compiler_command(ROOT, tmp_path, ROOT / "flatpak/desktop_entry.py")
    assert "--onefile" in command
    assert "--include-package=game_optimization_linux" in command
    assert "--enable-plugin=pyside6" in command
    assert any(item.startswith("--report=") for item in command)
    assert not any("--include-data-dir=data/data" in item or "--include-data-dir=libexec" in item for item in command)


def test_audit_rejects_internal_symlink_disguised_as_source(tmp_path):
    (tmp_path / "program").write_bytes(b"\x7fELF")
    (tmp_path / "leaked.py").symlink_to("program")
