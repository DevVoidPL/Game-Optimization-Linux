def test_desktop_removes_dependency_build_artifacts_before_app_audit():
    subprocess.run([sys.executable, str(ROOT / "flatpak/make-desktop-edition-manifest.py")], check=True)
    desktop = yaml.safe_load((ROOT / "flatpak/io.github.DevVoidPL.GameOptimizationLinux.desktop-edition.yml").read_text())
    commands = desktop["modules"][-1]["build-commands"]
    cleanup = "rm -rf /app/include /app/lib/debug && rm -f /app/lib/*.a"
    assert cleanup in commands
    assert commands.index(cleanup) < commands.index("python3 flatpak/desktop_release.py audit /app")


def test_app_audit_does_not_scan_sibling_runtime(tmp_path):
    app = tmp_path / "app"
    runtime = tmp_path / "usr"
    app.mkdir()
    runtime.mkdir()
    (runtime / "runtime.py").write_text("runtime source")
    assert policy().audit_tree(app) == []
    (app / "application.py").write_text("application source")
    assert policy().audit_tree(app)